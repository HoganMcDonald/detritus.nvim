local h = require("harness")
local t = h.t
local scope = require("detritus.scope")

describe("scope", function()
  it("resolves project and branch in a git repo", function()
    local repo = h.repo()
    local s = scope.resolve(repo)
    t.truthy(s.is_git)
    t.eq(s.project, repo)
    t.eq(s.branch, "main")
    t.eq(s.root, repo)
  end)

  it("tracks branch switches", function()
    local repo = h.repo()
    h.git({ "checkout", "-q", "-b", "feat/x" }, repo)
    t.eq(scope.resolve(repo).branch, "feat/x")
  end)

  it("shares the project across worktrees but splits by branch", function()
    local repo = h.repo()
    local wt = h.tmpdir() .. "/wt"
    h.git({ "worktree", "add", "-q", "-b", "feat", wt }, repo)
    local main, feat = scope.resolve(repo), scope.resolve(wt)
    t.eq(main.project, feat.project)
    t.eq(main.branch, "main")
    t.eq(feat.branch, "feat")
    t.eq(feat.root, (vim.uv.fs_realpath(wt)))
  end)

  it("labels a detached HEAD with the short sha", function()
    local repo = h.repo()
    local sha = h.git({ "rev-parse", "--short", "HEAD" }, repo)
    h.git({ "checkout", "-q", "--detach" }, repo)
    t.eq(scope.resolve(repo).branch, "@" .. sha)
  end)

  it("resolves from a subdirectory", function()
    local repo = h.repo()
    vim.fn.mkdir(repo .. "/sub/dir", "p")
    t.eq(scope.resolve(repo .. "/sub/dir").project, repo)
  end)

  it("works on an unborn branch", function()
    local dir = h.tmpdir()
    h.git({ "init", "-q", "-b", "fresh" }, dir)
    t.eq(scope.resolve(dir).branch, "fresh")
  end)

  it("falls back to the directory outside git", function()
    local dir = h.tmpdir()
    local s = scope.resolve(dir)
    t.falsy(s.is_git)
    t.eq(s.project, dir)
    t.eq(s.branch, "_")
  end)
end)
