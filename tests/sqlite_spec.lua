local h = require("harness")
local t = h.t
local sqlite = require("detritus.sqlite")

describe("sqlite", function()
  local function open()
    return sqlite.open(h.tmpdir() .. "/t.db")
  end

  it("round-trips ints, floats, text, null and booleans", function()
    local db = open()
    db:exec("CREATE TABLE x (i INTEGER, f REAL, s TEXT, n TEXT, b INTEGER)")
    db:run("INSERT INTO x VALUES (?, ?, ?, ?, ?)", { 42, 1.5, "héllo ⚠️", nil, true, n = 5 })
    local row = db:one("SELECT * FROM x")
    t.eq(row, { i = 42, f = 1.5, s = "héllo ⚠️", b = 1 })
    db:close()
  end)

  it("handles embedded quotes safely via parameters", function()
    local db = open()
    db:exec("CREATE TABLE x (s TEXT)")
    db:run("INSERT INTO x VALUES (?)", { "Robert'); DROP TABLE x;--" })
    t.eq(db:scalar("SELECT s FROM x"), "Robert'); DROP TABLE x;--")
  end)

  it("reports changes and last insert id", function()
    local db = open()
    db:exec("CREATE TABLE x (id INTEGER PRIMARY KEY, s TEXT)")
    db:run("INSERT INTO x (s) VALUES ('a')")
    t.eq(db:last_insert_rowid(), 1)
    t.eq(db:run("UPDATE x SET s = 'b'"), 1)
  end)

  it("rolls back a failed transaction", function()
    local db = open()
    db:exec("CREATE TABLE x (s TEXT)")
    t.throws(function()
      db:transaction(function()
        db:run("INSERT INTO x VALUES ('a')")
        error("boom", 0)
      end)
    end, "boom")
    t.eq(db:scalar("SELECT COUNT(*) FROM x"), 0)
  end)

  it("surfaces sql errors", function()
    local db = open()
    t.throws(function()
      db:exec("SELEKT 1")
    end, "sqlite exec failed")
  end)
end)
